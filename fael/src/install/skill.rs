//! Every skill fael ships, written into each client's skills dir (`install::run`).

use super::Ctx;
use std::path::Path;

/// Every file of every skill fael ships: (dir name under a client's skills dir, file, body)
/// (issue 01M4N42X). A file beside SKILL.md is a branch's reference, read on its pointer.
/// fael-content ships with fael crew, the owner's layer (decision 01M4SQ9B).
/// fael-plan and fael-sweep moved to fael crew (decision 01M5AF2H) — see MOVED.
pub(super) const SKILLS: [(&str, &str, &str); 3] = [
    ("fael", "SKILL.md", include_str!("../../skill/SKILL.md")),
    (
        "fael-debug",
        "SKILL.md",
        include_str!("../../skill/fael-debug/SKILL.md"),
    ),
    (
        "fael-review",
        "SKILL.md",
        include_str!("../../skill/fael-review/SKILL.md"),
    ),
];

/// Skills that moved to fael crew (decision 01M5AF2H). `install` removes the
/// old embedded copy but never a symlink — the crew copy is a symlink into
/// the crew checkout.
// ponytail: drop this cleanup once pre-move installs have aged out (embedded
// copies predate v0.74; remove ~v0.77) — otherwise it stays forever.
pub(super) const MOVED: [&str; 2] = ["fael-plan", "fael-sweep"];

pub(super) fn remove_moved(c: &Ctx, dir: &Path) -> Result<(), String> {
    for name in MOVED {
        let path = dir.join(name);
        // never a symlink: the crew copy is a link into the crew checkout
        if std::fs::symlink_metadata(&path).is_ok_and(|m| m.file_type().is_symlink()) {
            continue;
        }
        if !path.is_dir() {
            continue;
        }
        // only the copy fael wrote (the generated-by header line); a real dir
        // without it is someone's own copy and stays
        let ours = std::fs::read_to_string(path.join("SKILL.md"))
            .is_ok_and(|s| s.contains("generated by `fael install`"));
        if !ours {
            out!(c, "! {} is not fael's — left alone", path.display());
            continue;
        }
        if !c.dry {
            std::fs::remove_dir_all(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        }
        c.changed.set(c.changed.get() + 1);
        let verb = if c.dry { "would remove" } else { "removed" };
        out!(c, "  {verb} the moved skill {}", path.display());
    }
    Ok(())
}

/// The names fael's skills replace (decision fael-board:skill-names). A link under one
/// goes when it points into a fael checkout; a real dir is someone's own copy and stays.
const RETIRED: [&str; 5] = [
    "plan-with-marketing",
    "plan-with-pony",
    "review-pony",
    "debug-pony",
    "git-ship",
];

pub(super) fn retire(c: &Ctx, dir: &Path) -> Result<(), String> {
    for name in RETIRED {
        let link = dir.join(name);
        // read_link, not canonicalize: a link whose target is gone goes too
        let Ok(t) = std::fs::read_link(&link) else {
            continue;
        };
        let t = t.to_string_lossy().replace('\\', "/");
        if !t.ends_with(&format!("fael/skill/{name}")) {
            continue;
        }
        if !c.dry {
            std::fs::remove_file(&link)
                .or_else(|_| std::fs::remove_dir(&link))
                .map_err(|e| format!("{}: {e}", link.display()))?;
        }
        c.changed.set(c.changed.get() + 1);
        let verb = if c.dry { "would remove" } else { "removed" };
        out!(c, "  {verb} the retired skill link {}", link.display());
    }
    Ok(())
}

pub(super) fn skill(c: &Ctx, path: &Path, body: &str) -> Result<(), String> {
    // a dev's link into a fael checkout (`…/fael/skill[/<name>]`) gives way to the release
    // copy — a write through it would land in that checkout; any other link is not fael's
    let dir = path.parent().unwrap_or(path);
    if std::fs::symlink_metadata(dir).is_ok_and(|m| m.file_type().is_symlink()) {
        let ours = dir.canonicalize().is_ok_and(|t| {
            t.ends_with("fael/skill") || t.parent().is_some_and(|p| p.ends_with("fael/skill"))
        });
        if !ours {
            out!(c, "! {} is a link, not fael's — left alone", dir.display());
            return Ok(());
        }
        if !c.dry {
            std::fs::remove_file(dir)
                .or_else(|_| std::fs::remove_dir(dir))
                .map_err(|e| format!("{}: {e}", dir.display()))?;
        }
        c.write(path, body)?;
        c.say("skill (was a link into a checkout)", path);
        return Ok(());
    }
    match std::fs::read_to_string(path) {
        Ok(cur) if cur == body => out!(c, "skill already at {}", path.display()),
        Ok(cur) if !cur.contains("generated by `fael install`") => {
            out!(c, "! {} is not fael's — left alone", path.display());
        }
        Ok(cur) => {
            // a hand edit under the marker would vanish with the rewrite: keep
            // the old copy beside it (one .bak, the last install's)
            // ponytail: every changed skill gets a .bak, edited or not; stamp a
            // hash in the marker if telling an edit from an old release matters
            let bak = path.with_extension("md.bak");
            c.write(&bak, &cur)?;
            c.write(path, body)?;
            c.say("skill", path);
            let verb = if c.dry { "would keep" } else { "kept" };
            out!(c, "  {verb} the old skill as {}", bak.display());
        }
        Err(_) => {
            c.write(path, body)?;
            c.say("skill", path);
        }
    }
    Ok(())
}
